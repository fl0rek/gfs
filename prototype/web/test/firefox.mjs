// The page in Firefox (WebDriver BiDi): boot, system, a prompt with bash, reload.
import puppeteer from "puppeteer-core";
const browser = await puppeteer.launch({ browser: "firefox", executablePath: process.env.FIREFOX ?? "/opt/pw-browsers/firefox-1555/firefox/firefox", headless: true, protocolTimeout: 180000 });
const page = (await browser.pages())[0] ?? (await browser.newPage());
page.on("console", (m) => { if (m.type() === "error" || /gfs:|switch|system/.test(m.text())) console.log(`  [ff:${m.type()}] ${m.text().slice(0, 200)}`); });
page.on("pageerror", (e) => console.log(`  [pageerror] ${e.message}`));
let failures = 0;
const check = (c, m) => { console.log(`${c ? "ok " : "FAIL"} ${m}`); if (!c) failures++; };
const state = () => page.evaluate(() => window.__pi.state());
const call = (req) => page.evaluate((r) => window.__pi.worker.call(r), req);
const tool = (name, params) => call({ method: "debugTool", name, params });
const text = (r) => r.content.map((c) => c.text).join("");
const t0 = Date.now();
await page.goto(process.argv[2] ?? "http://localhost:4173/", { waitUntil: "load" });
console.log("  UA:", await page.evaluate(() => navigator.userAgent), "| crossOriginIsolated:", await page.evaluate(() => crossOriginIsolated));
await page.waitForFunction(() => window.__pi?.state().info !== null || window.__pi?.state().error, { timeout: 60000 });
let st = await state();
check(st.info && !st.error, `worker initialised in ${Date.now() - t0}ms (${st.error ?? st.statusText})`);
check(st.info?.persistence === "opfs", `persistence: ${st.info?.persistence}`);
await page.waitForFunction(() => window.__pi.state().info?.system || /unavailable|refused|failed/.test(window.__pi.state().statusText), { timeout: 180000 });
st = await state();
check(st.info.system && !/unavailable/.test(st.statusText), `system up in ${Date.now() - t0}ms: ${st.info.system?.name?.slice(0, 50) ?? st.statusText}`);
const r = await tool("bash", { command: "bash --version | head -1; echo a b c | awk '{print $2}'; seq 3 | grep 2" });
check(!r.isError && /wasm32-nix-wasix/.test(text(r)) && /^b$/m.test(text(r)) && /^2$/m.test(text(r)), `bash+awk+grep in Firefox: ${JSON.stringify(text(r)).slice(0, 120)}`);
await page.type("textarea", "Firefox check");
await page.keyboard.press("Enter");
await page.waitForFunction(() => window.__pi.state().busy, { timeout: 10000 });
await page.waitForFunction(() => !window.__pi.state().busy, { timeout: 120000 });
st = await state();
const results = st.transcript.filter((m) => m.role === "toolResult");
check(results.length >= 4 && results.filter((x) => x.toolName !== "fetch").every((x) => !x.isError), `mock prompt ran ${results.length} tool calls (${results.map((x) => `${x.toolName}${x.isError ? "!" : ""}`).join(" ")})`);
const log = await call({ method: "log", comb: "workspace" });
check(log.some((e) => e.tool_name === "bash"), "bash entry in history");
await page.reload({ waitUntil: "load" });
await page.waitForFunction(() => window.__pi?.state().info !== null, { timeout: 60000 });
const log2 = await call({ method: "log", comb: "workspace" });
check(log2.length === log.length, `history persisted across reload in Firefox (${log2.length} entries)`);
await browser.close();
console.log(failures ? `${failures} FAILED` : "all checks passed");
process.exit(failures ? 1 : 0);
