// Switch /nix to Nix-built bash + grep (raw wasm modules), keeping Wasmer's coreutils; run things.
import puppeteer from "puppeteer-core";
const [bashSha, grepSha] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: process.env.CHROME ?? "/opt/pw-browsers/chromium-1248/chrome-linux64/chrome", headless: true, protocolTimeout: 120000, args: ["--no-sandbox", "--disable-gpu"] });
const page = await browser.newPage();
page.on("pageerror", (e) => console.log(`  [pageerror] ${e.message}`));
const call = (req) => page.evaluate((r) => window.__pi.worker.call(r), req);
const tool = (name, params) => call({ method: "debugTool", name, params });
const text = (r) => r.content.map((c) => c.text).join("");
let failures = 0;
const check = (c, m) => { console.log(`${c ? "ok " : "FAIL"} ${m}`); if (!c) failures++; };
await page.goto("http://localhost:4173/", { waitUntil: "load" });
await page.waitForFunction(() => window.__pi.state().info !== null, { timeout: 90000 });
const m = JSON.parse(text(await tool("read", { path: "/nix/machine.json" })));
m.name = "nix-built bash + grep, wasmer coreutils";
m.packages = m.packages.filter((p) => !p.name.startsWith("wasmer/bash"));
m.packages.unshift({ kind: "wasm", name: "nix:bash.wasm", url: "machine/bash.wasm", sha256: bashSha, command: "bash" }, { kind: "wasm", name: "nix:grep.wasm", url: "machine/grep.wasm", sha256: grepSha, command: "grep" });
const t0 = Date.now();
await tool("write", { path: "/nix/machine.json", content: JSON.stringify(m, null, 2) + "\n" });
await new Promise((r) => setTimeout(r, 500));
let st = await page.evaluate(() => window.__pi.state());
check(!st.error, `switch to nix-built bash (${Date.now() - t0}ms): ${st.error ?? "ok"}`);
check(/nix-built/.test(st.info.system?.name ?? ""), `system: ${st.info.system?.name}`);
const v = await tool("bash", { command: "bash --version | head -1; echo pipes work | grep -o works; printf 'a\\nb\\nc\\n' | grep -c .; x=$((6*7)); echo answer=$x; ls" });
check(!v.isError, `bash run ok`);
console.log("  " + text(v).trim().split("\n").join("\n  "));
check(/answer=42/.test(text(v)) && /works/.test(text(v)) && /^3$/m.test(text(v)), "nix-built bash: pipes, grep, arithmetic");
const w = await tool("bash", { command: "echo from-nix-bash > nix-note.txt && cat nix-note.txt" });
check(!w.isError && /from-nix-bash/.test(text(w)), "writes through the mirror still land in the comb");
const log = await call({ method: "log", comb: "workspace" });
check(log[0].summary.added.includes("nix-note.txt"), "…as a history entry");
await browser.close();
console.log(failures ? `${failures} FAILED` : "all checks passed");
process.exit(failures ? 1 : 0);
